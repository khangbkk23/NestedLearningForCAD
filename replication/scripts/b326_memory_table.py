"""B326 M3: three-column persistent-memory table for detector F (stdlib only, no torch, no data).

Inputs: the `cost.persistent_bytes` dicts of Khang's sealed runs, the literature memory table he compiled, and the
M2 job metrics (measured int8 payload). Khang's files are pinned by *text hash* (SHA-256 after CRLF -> LF, because a
Windows checkout may rewrite line endings; it is not a hash of the original bytes). Changed inputs are refused.

    python -I -B replication/scripts/b326_memory_table.py --f hope_s_02_RESULT.json --c nar_lite_01_RESULT.json \
        --literature docs/benchmarks/cad_literature_2026-10-27/table2_memory.csv \
        --m2 replication/experiments/B326/runs/b326-m2-20261119-01/metrics.json --out memory_table.md

The two RESULT.json files are outputs of Khang's local runs (`results/hope_cad/hope_s_02/RESULT.json` and
`results/hope_cad/nar_lite_01/RESULT.json`), which are not in git. The published
`replication/experiments/B326/memory_table.md` was generated by this script from the pinned inputs; the wording of the
generated prose was afterwards translated from Vietnamese to English, the numbers are unchanged.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path

PINS = {  # text hashes, see text_sha
    'f': '5c48a639ab0aa405a81f9643d39a74dad13ba0c093977008ac22b6b23419678e',     # hope_s_02/RESULT.json (arm F)
    'c': 'bd66bb7568dd376d363fbcbea87cb5ccc14ac49acec6fc6af9d304c750a668d7',     # nar_lite_01/RESULT.json (arm C)
    'lit': 'eecaf1b4e696b978c0d4d6e2b0ce0b7c7ef512d95dff2ace5e62d9f92a2bab4a',   # table2_memory.csv
}
TASKS, SITES, RANK = 15, 34, 8
LIT = ('ReplayCAD', 'CADIC (2.5k)', 'CADIC (10k, default)', 'GCR', 'ONER', 'UCAD', 'DNE', 'PatchCore-CL')


def text_sha(path):
    """Text hash: SHA-256 of the file with CRLF normalised to LF. Accepts both line-ending forms of the same text;
    it does not prove the original bytes are identical."""
    return hashlib.sha256(Path(path).read_bytes().replace(b'\r\n', b'\n')).hexdigest()


def mb(x):
    return x / 1e6


def int8_archive_bytes(archive_bf16):
    """Card s2 M2: int8 per rank component + fp16 scales (8 for A rows, 8 for B columns per site and task)."""
    params = archive_bf16 // 2
    return params + TASKS * SITES * 2 * RANK * 2


def measured_int8(m2, archive_bf16):
    """Measured int8 payload from job M2 (must be identical across seeds); also checked against the card formula."""
    got = {v['quant']['stored_bytes_int8_plus_scales'] for v in m2['seeds'].values()}
    bf16 = {v['quant']['bf16_bytes'] for v in m2['seeds'].values()}
    if m2.get('label') != 'INT8_LOSSLESS' or len(got) != 1 or bf16 != {archive_bf16}:
        raise SystemExit(f'M2 metrics do not match hope_s_02: label {m2.get("label")}, bytes {got}, bf16 {bf16}')
    a8 = got.pop()
    if a8 != int8_archive_bytes(archive_bf16):
        raise SystemExit(f'measured int8 bytes {a8} differ from the formula {int8_archive_bytes(archive_bf16)}')
    return a8


def table(f, c, lit_rows, a8):
    pf, pc = f['cost']['persistent_bytes'], c['cost']['persistent_bytes']
    rows = []
    for name, p in (('F (γ 2.1), Khang hope_s_02, bf16', pf), ('C (γ 0), Khang nar_lite_01, bf16', pc)):
        cl = p['archive'] + p['policy']
        rows.append((name, cl, p['shared_decoder'], p['shared_encoder']))
    lines = ['| Configuration | (1) CL state (archive + policy) | (2) BASE, method-specific | '
             '(3) Public encoder | Total |', '| --- | ---: | ---: | ---: | ---: |']
    for name, cl, base, enc in rows:
        lines.append(f'| {name} | {mb(cl):.2f} MB | {mb(base):.2f} MB | {mb(enc):.2f} MB | {mb(cl + base + enc):.2f} MB |')
    a32 = pf['archive'] * 2
    lines.append(f'| F, archive derived at fp32 (same dtype as most inferred literature numbers) '
                 f'| {mb(a32 + pf["policy"]):.2f} MB '
                 f'| {mb(pf["shared_decoder"]):.2f} MB | {mb(pf["shared_encoder"]):.2f} MB | '
                 f'{mb(a32 + pf["policy"] + pf["shared_decoder"] + pf["shared_encoder"]):.2f} MB |')
    lines.append(f'| F + M2 (int8 archive, tensor payload measured in job M2, `INT8_LOSSLESS`, '
                 f'[results](runs/b326-m2-20261119-01/results.md)) '
                 f'| {mb(a8 + pf["policy"]):.2f} MB | {mb(pf["shared_decoder"]):.2f} MB '
                 f'| {mb(pf["shared_encoder"]):.2f} MB | {mb(a8 + pf["policy"] + pf["shared_decoder"] + pf["shared_encoder"]):.2f} MB |')
    lit = ['| Method (literature) | MB, MVTec 15 | Growth with tasks | Source of the number |', '| --- | ---: | --- | --- |']
    for r in lit_rows:
        if r['Method'] in LIT:
            lit.append(f"| {r['Method']} | {r['Persistent_MB_MVTec15']} | {r['Growth_with_tasks']} | {r['Source']} |")
    per_task = pf['archive'] / TASKS
    return lines, lit, per_task


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--f', required=True)
    p.add_argument('--c', required=True)
    p.add_argument('--literature', required=True)
    p.add_argument('--m2', required=True)
    p.add_argument('--out', required=True)
    a = p.parse_args()
    if text_sha(a.f) != PINS['f'] or text_sha(a.c) != PINS['c']:
        raise SystemExit('result files differ from the pinned hope_s_02 / nar_lite_01 RESULT.json')
    if text_sha(a.literature) != PINS['lit']:
        raise SystemExit('literature CSV differs from the pinned table2_memory.csv')
    f, c = json.loads(Path(a.f).read_text(encoding='utf8')), json.loads(Path(a.c).read_text(encoding='utf8'))
    pf = f['cost']['persistent_bytes']
    a8 = measured_int8(json.loads(Path(a.m2).read_text(encoding='utf8')), pf['archive'])
    lit_rows = list(csv.DictReader(open(a.literature, encoding='utf8')))
    lines, lit, per_task = table(f, c, lit_rows, a8)
    out = Path(a.out)
    if out.exists():
        raise SystemExit(f'refusing to overwrite {out}')
    own_bf16 = pf['archive'] + pf['policy'] + pf['shared_decoder']
    own_int8 = a8 + pf['policy'] + pf['shared_decoder']
    text = '\n'.join([
        '# B326 M3: persistent memory of the detector, three columns',
        '',
        'Generated by `replication/scripts/b326_memory_table.py`; byte counts come from `cost.persistent_bytes` in '
        f"Khang's RESULT files (F: `hope_s_02`, text hash `{text_sha(a.f)[:12]}…`; C: `nar_lite_01`, text hash "
        f'`{text_sha(a.c)[:12]}…`). A text hash is SHA-256 after CRLF to LF, not a hash of the original bytes. '
        'The F + M2 row uses the int8 payload measured in [job M2](runs/b326-m2-20261119-01/metrics.json); the script '
        'checks it against the formula in the card. MB = 10^6 bytes. Card: [B326](card.md) section 2, M3.',
        '',
        *lines,
        '',
        '**Headline number:** the method-specific state, i.e. column (1) + column (2) of F. M1 did not give '
        '`BASE_PORTABLE` (regenerating on Windows gave a different SHA-256 from Linux), so BASE stays counted.',
        f'- bf16: {mb(own_bf16):.1f} MB (headline).',
        f'- With the M2 int8 archive (no measurable quality change): {mb(own_int8):.1f} MB (secondary).',
        '',
        'BASE is required at inference, like the generator that ReplayCAD does not count (card section 5, item 8). Column (1) '
        'is the additional CL state: usable only when BASE (column 2) and the encoder (column 3) are available. It '
        'cannot score on its own.',
        '',
        '**About the int8 number:**',
        '- It is the tensor payload (int8 + fp16 scales), without the `torch.save` container.',
        '- Job M2 scored an in-RAM dequantised copy built from exactly the stored tensors.',
        '- Two paths are untested: reloading `archive_int8.pt` from file and dequantising it, and resuming training '
        'from the int8 archive. Claims about file-based deployment or resume need their own check.',
        '',
        f'**Growth with tasks:** the archive grows linearly, {mb(per_task):.2f} MB/task in bf16 and '
        f'{mb(a8 / TASKS):.2f} MB/task in int8. UCAD preallocates for 15 tasks; CADIC is constant.',
        '',
        "**C's policy is larger than F's**, because C's warm checkpoint also stores the fixed initialisation `phi` "
        '(3.39 MB); F stores only λ.',
        '',
        '**Dtype:** F is counted in bf16; most literature numbers are inferred at FP32 (column "Source of the number"). '
        'For a same-dtype comparison use the fp32 row of F; that row only doubles the archive, BASE and encoder are '
        'counted as in the other rows.',
        '',
        '**Scope of the comparison:**',
        '- The literature table counts only the persistent CL state, not the frozen backbone, so it compares with '
        'column (1) only. The self-reported / inferred label is kept in "Source of the number".',
        '- Column (2) has no counterpart in the literature (other methods use a pretrained backbone). It must be '
        'reported next to column (1), neither merged nor dropped.',
        '',
        *lit,
        '',
        f"Literature table: Khang's `table2_memory.csv` (text hash `{text_sha(a.literature)[:12]}…`, pinned). The "
        'column "Source of the number" records whether a number is self-reported or inferred.',
        ''])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf8', newline='\n')
    print(text)


if __name__ == '__main__':
    main()
