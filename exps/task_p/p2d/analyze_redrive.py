"""Unpinned re-drive of the pinned P2d analysis after a mechanical metadata defect.

`exps/task_p/p2d/analyze.py` is hash-pinned by the locked protocol and must not be
edited. Its per-order loop reads `protocol["orders"][order]` as a mapping (the shape
P2's own lock used), while the P2d lock stored `orders` as a plain list of order
names; the pinned code therefore crashed after it had already computed and written
the four heavy artifacts (point_metrics, bootstrap_samples, score_separation,
reference_reconciliation). No metric, bootstrap, threshold, decision or plotting
logic differs here: this driver only supplies the protocol view with `orders` in the
mapping shape the pinned code was written against, then calls the pinned `analyze()`
unchanged. The four artifacts regenerated by the pinned body are compared bitwise
against the first-attempt copies in `analysis_redrive_reconciliation.json`.
"""
from __future__ import annotations

from exps.task_p.p2d import analyze as analyze_module
from exps.task_p.p2d.data import ORDERS
from exps.task_p.p2d.experiment import load_protocol as locked_protocol


def patched_protocol():
    protocol = locked_protocol()
    protocol["orders"] = {order: list(ORDERS[order]) for order in ORDERS}
    return protocol


analyze_module.load_protocol = patched_protocol

if __name__ == "__main__":
    analyze_module.analyze()
