from abc import ABC, abstractmethod

class BenchmarkMethodAdapter(ABC):
    @abstractmethod
    def fit_task(self, task_id, task_name, train_loader) -> dict: ...
    @abstractmethod
    def score_batch(self, batch) -> dict: ...
    @abstractmethod
    def state_dict(self) -> dict: ...
    @abstractmethod
    def load_state_dict(self, state) -> None: ...
    @abstractmethod
    def memory_stats(self) -> dict: ...
    @abstractmethod
    def method_metadata(self) -> dict: ...
